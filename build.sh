#!/bin/bash
# Build Momo.app — a double-clickable, ad-hoc signed bundle.
set -euo pipefail
cd "$(dirname "$0")"

APP="Momo.app"
BIN="momo"

echo "→ built-in key"
# Bake the local CMC key into the binary, obfuscated, so the app works out of
# the box and the key never appears in Settings or settings.json. The key is
# read from $CMC_API_KEY, ~/momo/.env, or the legacy apiKey in the local
# settings.json — all on this Mac, never committed. BuiltinKey.swift is
# gitignored; a build without a local key just ships without a built-in key.
KEY_SOURCE=""
if [[ -n "${CMC_API_KEY:-}" ]]; then KEY_SOURCE="$CMC_API_KEY";
elif [[ -f .env ]]; then KEY_SOURCE="$(grep -m1 '^CMC_API_KEY=' .env 2>/dev/null | cut -d= -f2- | tr -d '[:space:]' || true)";
elif [[ -f "$HOME/Library/Application Support/Momo/settings.json" ]]; then KEY_SOURCE="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("apiKey",""))' "$HOME/Library/Application Support/Momo/settings.json" 2>/dev/null || true)";
fi
if [[ -n "$KEY_SOURCE" ]]; then
  python3 - "$KEY_SOURCE" <<'PYEOF'
import sys
key = sys.argv[1].strip()
ob = ", ".join(str(b ^ 0xA5) for b in key.encode())
open("BuiltinKey.swift", "w").write(
  "// Generated by build.sh - do not edit, do not commit.\n"
  "// The built-in CMC key, XOR-obfuscated. Decoded only in memory.\n"
  "enum BuiltinKey {\n"
  "    static let value: String = {\n"
  f"        let bytes: [UInt8] = [{ob}]\n"
  "        return String(bytes: bytes.map { $0 ^ 0xA5 }, encoding: .utf8) ?? \"\"\n"
  "    }()\n"
  "}\n")
print("  built-in key baked in (obfuscated, not in repo)")
PYEOF
elif [[ ! -f BuiltinKey.swift ]]; then
  printf '// Generated by build.sh - no local key found, so no built-in key.\n// The user can add their own key in Settings.\nenum BuiltinKey {\n    static let value: String = ""\n}\n' > BuiltinKey.swift
  echo "  (no local key found - app will ask for one in Settings)"
fi

echo "→ compiling"
swiftc -O -o "$BIN" main.swift MomoFeed.swift BuiltinKey.swift -framework Cocoa -framework WebKit

echo "→ assembling $APP"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cp "$BIN" "$APP/Contents/MacOS/momo"
cp skin.html "$APP/Contents/Resources/skin.html"
cp settings.html "$APP/Contents/Resources/settings.html"
cp chrome-arcs.js "$APP/Contents/Resources/chrome-arcs.js"
cp anodized-ink.js "$APP/Contents/Resources/anodized-ink.js"
cp finance-bento.js "$APP/Contents/Resources/finance-bento.js"
cp elegant-contents.js "$APP/Contents/Resources/elegant-contents.js"
cp laser-flow.js "$APP/Contents/Resources/laser-flow.js"
cp plasma-wave.js "$APP/Contents/Resources/plasma-wave.js"
cp assets/AppIcon.icns "$APP/Contents/Resources/Momo.icns"

cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>              <string>Momo</string>
    <key>CFBundleDisplayName</key>       <string>Momo</string>
    <key>CFBundleIdentifier</key>        <string>com.suvog.momo</string>
    <key>CFBundleExecutable</key>        <string>momo</string>
    <key>CFBundlePackageType</key>       <string>APPL</string>
    <key>CFBundleShortVersionString</key><string>0.1.1</string>
    <key>CFBundleVersion</key>           <string>2</string>
    <key>LSMinimumSystemVersion</key>    <string>13.0</string>
    <key>LSUIElement</key>               <true/>
    <key>CFBundleIconFile</key>           <string>Momo</string>
    <key>NSHighResolutionCapable</key>   <true/>
    <key>NSHumanReadableCopyright</key>  <string>Momo · CMC API Hackathon 2026</string>
</dict>
</plist>
PLIST

echo "→ signing (ad-hoc)"
codesign --force --deep -s - "$APP" 2>/dev/null || echo "  (codesign skipped)"

# Restart the running copy so a build always ends with the new binary live.
# `./build.sh --no-launch` builds without touching what is running.
if [[ "${1:-}" != "--no-launch" ]]; then
  echo "→ restarting Momo"
  pkill -f "Momo.app/Contents/MacOS/momo" 2>/dev/null || true
  sleep 0.4
  open -a "$(pwd)/$APP" || open "$(pwd)/$APP"
fi

echo "done: $(pwd)/$APP"
